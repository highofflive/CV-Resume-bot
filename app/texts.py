def format_cv_card(cv) -> str:
    """Форматує об'єкт моделі CV із бази даних у текстове повідомлення."""
    return (
        f"📄 <b>Твоє збережене резюме:</b>\n\n"
        f"👤 <b>Ім'я:</b> {cv.name}\n"
        f"💼 <b>Посада:</b> {cv.position}\n"
        f"📞 <b>Контакти:</b> {cv.contacts}\n"
        f"🛠 <b>Навички:</b> {cv.skills}\n"
        f"📚 <b>Досвід та освіта:</b>\n{cv.experience}"
    )